/**
 * Проверяет, что значение ещё не заполнено заказчиком.
 * Единая точка проверки placeholder'ов во всём проекте — не дублировать логику.
 *
 * @param {*} value Проверяемое значение.
 * @returns {boolean} true, если значение отсутствует или помечено [ЗАПОЛНИТЬ].
 */
export function isPlaceholder(value) {
  if (value === null || value === undefined) {
    return true;
  }
  const text = String(value).trim();
  return text === '' || text.includes(PLACEHOLDER);
}

/**
 * Приводит любой ввод к существующему филиалу.
 *
 * Пустое, неизвестное или отсутствующее значение превращается в основной
 * филиал из CONFIG.primaryBranch. Это важно для маршрутизации заявок:
 * раньше запасным всегда был Липецк, и на ереванском сайте заявка без
 * выбранного филиала ушла бы не в тот чат Telegram.
 *
 * @param {unknown} value Идентификатор филиала из формы или payload.
 * @returns {'am'|'ru'} Гарантированно существующий идентификатор.
 */
export function normalizeBranch(value) {
  const id = typeof value === 'string' ? value.trim().toLowerCase() : '';
  if (Object.prototype.hasOwnProperty.call(CONFIG.branches, id)) {
    return id;
  }
  const primary = CONFIG.primaryBranch;
  if (Object.prototype.hasOwnProperty.call(CONFIG.branches, primary)) {
    return primary;
  }
  // Страховка: конфиг повреждён или primaryBranch задан с опечаткой.
  return Object.keys(CONFIG.branches)[0];
}

/**
 * Проверяет, готов ли филиал принимать заявки.
 * Учитывает и настройки транспорта, и заполненность целевого чата.
 *
 * @param {'ru'|'am'} branchId Идентификатор филиала.
 * @returns {{ok: boolean, missing: string[]}} Статус и список незаполненных ключей.
 */
export function isBranchReady(branchId) {
  const missing = [];
  const branch = CONFIG.branches[branchId];

  if (!branch) {
    return { ok: false, missing: [`branches.${branchId}`] };
  }

  const chat = CONFIG.telegram.chats[branch.telegramBranch];
  if (!chat) {
    missing.push(`telegram.chats.${branch.telegramBranch}`);
  } else {
    if (!chat.enabled) {
      missing.push(`telegram.chats.${branch.telegramBranch}.enabled (выключен)`);
    }
    if (isPlaceholder(chat.chatId)) {
      missing.push(`TELEGRAM_CHAT_ID_${branch.telegramBranch.toUpperCase()}`);
    }
  }

  // Режим 'off' проверяется раньше токена и отвечает «не готов» даже при
  // заполненном чате. Без этой ветки сайт с выключенной отправкой провалился
  // бы в проверку botToken и сообщил бы посетителю про непонятный ключ
  // доставки вместо честного «приём заявок выключен».
  const mode = CONFIG.telegram.transport;
  if (mode === 'off') {
    return { ok: false, missing: ['telegram.transport = off (отправка выключена)'] };
  }

  if (mode === 'proxy') {
    if (isPlaceholder(CONFIG.telegram.proxyUrl)) {
      // Не «TELEGRAM_PROXY_URL»: это ключ в config.js, а не переменная
      // окружения функции. Раньше обе сущности назывались одинаково, и при
      // развёртывании было непонятно, что именно осталось заполнить.
      missing.push('CONFIG.telegram.proxyUrl');
    }
  } else if (isPlaceholder(CONFIG.telegram.botToken)) {
    missing.push('TELEGRAM_BOT_TOKEN');
  }

  return { ok: missing.length === 0, missing };
}

